export function findTimezone(id) {
  if (!id) return null;
  const match = TIMEZONES.find(t => t.id === id);
  if (match) return match;
  const lower = String(id).toLowerCase();
  return TIMEZONES.find(t =>
    t.id.toLowerCase() === lower ||
    t.countryCode.toLowerCase() === lower ||
    t.country.toLowerCase() === lower ||
    t.title.toLowerCase() === lower ||
    t.searchTerms.some(st => st.toLowerCase().includes(lower))
  ) || null;
}

export function searchTimezones(query) {
  if (!query || typeof query !== "string") {
    return TIMEZONES.map(tz => ({
      tz,
      matchedTerm: tz.searchTerms[0] || tz.country,
      query: ""
    }));
  }

  const q = query.trim().toLowerCase();
  if (!q) {
    return TIMEZONES.map(tz => ({
      tz,
      matchedTerm: tz.searchTerms[0] || tz.country,
      query: ""
    }));
  }

  const qNoSpace = q.replace(/\s+/g, "");
  const results = [];

  for (const tz of TIMEZONES) {
    let bestTerm = null;
    let bestScore = 0;

    for (const term of tz.searchTerms) {
      const termLower = term.toLowerCase();
      if (!termLower.includes(q)) continue;

      const cityName = termLower.split(",")[0].trim();
      let score = 1;
      if (termLower.startsWith(q)) {
        score = 2;
      }
      if (cityName.includes(q)) {
        score = 3;
      }
      if (cityName.startsWith(q)) {
        score = 4;
      }
      if (cityName === q) {
        score = 5;
      }

      if (score > bestScore) {
        bestScore = score;
        bestTerm = term;
      }
    }

    if (bestTerm) {
      results.push({
        tz,
        matchedTerm: bestTerm,
        query
      });
    } else {
      const titleMatch = tz.title.toLowerCase().includes(q);
      const countryMatch = tz.country.toLowerCase().includes(q);
      const codeMatch = tz.countryCode.toLowerCase() === q;
      const offsetMatch = tz.offset.toLowerCase().replace(/\s+/g, "").includes(qNoSpace);

      if (titleMatch || countryMatch || codeMatch || offsetMatch) {
        results.push({
          tz,
          matchedTerm: tz.searchTerms[0] || tz.country,
          query
        });
      }
    }
  }

  return results;
}

export function highlightMatch(text, query) {
  if (!text) return "";
  if (!query || typeof query !== "string") return escapeHtml(text);
  const q = query.trim();
  if (!q) return escapeHtml(text);

  const lowerText = text.toLowerCase();
  const lowerQ = q.toLowerCase();
  let result = "";
  let lastIdx = 0;
  let found = lowerText.indexOf(lowerQ, lastIdx);

  if (found === -1) {
    return escapeHtml(text);
  }

  while (found !== -1) {
    result += escapeHtml(text.slice(lastIdx, found));
    result += `<strong>${escapeHtml(text.slice(found, found + q.length))}</strong>`;
    lastIdx = found + q.length;
    found = lowerText.indexOf(lowerQ, lastIdx);
  }
  result += escapeHtml(text.slice(lastIdx));
  return result;
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
